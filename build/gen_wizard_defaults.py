#!/usr/bin/env python3
"""Generate build/wizard_defaults.isi — the installer wizard's pre-filled values.

Reads build_config.toml (gitignored) and writes ISPP #define lines that
disc2jelly.iss #includes. A generated file rather than ISCC /D switches
because the WebDAV password goes through here, and a command line is visible
to every process on the build machine.

SECURITY: whatever lands in this file is compiled into Setup.exe and is
recoverable from it with `strings`. That is the deliberate trade for an
installer that asks the end user nothing. Use an app password scoped to the
destination share, and never publish such an installer. Leave
`webdav_password` empty in build_config.toml and the wizard asks for it on
the target machine instead.

  python build/gen_wizard_defaults.py
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = REPO_ROOT / "build_config.toml"
OUTPUT_PATH = Path(__file__).resolve().parent / "wizard_defaults.isi"

# (ISPP define, config key, default)
FIELDS = [
    ("DefaultDestinationKind", "destination_kind", "local"),
    ("DefaultLocalPath", "local_path", ""),
    ("DefaultWebdavUrl", "webdav_url", ""),
    ("DefaultWebdavUser", "webdav_user", ""),
    ("DefaultWebdavPassword", "webdav_password", ""),
]

HEADER = """; Generated by build/gen_wizard_defaults.py from build_config.toml.
; DO NOT EDIT and do not commit — it can contain a WebDAV password.
"""


def ispp_string(value: str) -> str:
    """Quote a value as an ISPP string literal (a quote is doubled)."""
    return '"' + str(value).replace('"', '""') + '"'


def render(cfg: dict) -> str:
    lines = [HEADER]
    for define, key, default in FIELDS:
        lines.append(f"#define {define} {ispp_string(cfg.get(key, default))}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=CONFIG_PATH)
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH)
    args = parser.parse_args(argv)

    if args.config.is_file():
        cfg = tomllib.loads(args.config.read_text(encoding="utf-8"))
    else:
        print(f"note: {args.config} not found — the wizard will ask for everything")
        cfg = {}

    if cfg.get("webdav_password"):
        print("WARNING: the WebDAV password is being compiled into Setup.exe so "
              "the wizard can skip its credentials page. It is recoverable with "
              "`strings`. Do not publish this installer.")

    # UTF-8 with BOM: Inno Setup 6 is Unicode and identifies script encoding by
    # the BOM; without one a non-ASCII path or password is read as ANSI.
    args.output.write_text(render(cfg), encoding="utf-8-sig")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
